"""
campus.py - simulated campus world for the delivery-robot project (stage 1).
Do NOT edit this file. The grader uses its own copy.

The world is generated deterministically from a seed, so every team can get its own
campus (use your team's seed) and the grader can re-create exactly the same campus.
You get the world only through the API of the World object (see README / project document).
Every call to edges_from / edges_to is COUNTED against a budget.
"""
import math, random, heapq, types
from collections import namedtuple, deque

Edge = namedtuple("Edge", "to length time energy")


class BudgetExceeded(Exception):
    pass


class _Data:
    pass


def _strongly_connected(n, out):
    def reach(adj):
        seen = {0}; dq = deque([0])
        while dq:
            u = dq.popleft()
            for v in adj[u]:
                if v not in seen:
                    seen.add(v); dq.append(v)
        return len(seen) == n
    rev = [[] for _ in range(n)]
    for u in range(n):
        for e in out[u]:
            rev[e.to].append(u)
    return reach([[e.to for e in out[u]] for u in range(n)]) and reach(rev)


def generate_data(seed, n=60, cap=60, charger_frac=0.12, one_way_frac=0.15, wait_frac=0.15,
                  speed=2.0, charge_time=6):
    rng = random.Random(seed)
    pts = []
    while len(pts) < n:
        p = (rng.uniform(0, 1000), rng.uniform(0, 700))
        if all(math.dist(p, q) >= 45 for q in pts):
            pts.append(p)
    pts = [(round(x), round(y)) for x, y in pts]
    dist = lambda i, j: math.dist(pts[i], pts[j])
    pairs = set()
    for i in range(n):
        near = sorted(range(n), key=lambda j: dist(i, j))[1:4]
        for j in near:
            pairs.add((min(i, j), max(i, j)))
    # make sure the campus is connected (Kruskal)
    parent = list(range(n))
    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]; a = parent[a]
        return a
    for i, j in sorted(pairs, key=lambda p: dist(*p)):
        parent[find(i)] = find(j)
    for i, j in sorted(((i, j) for i in range(n) for j in range(i + 1, n)), key=lambda p: dist(*p)):
        if find(i) != find(j):
            parent[find(i)] = find(j); pairs.add((i, j))
    wait = [rng.randint(5, 25) if rng.random() < wait_frac else 0 for _ in range(n)]
    chargers = frozenset(rng.sample(range(n), max(2, int(n * charger_frac))))
    out = [[] for _ in range(n)]
    for (i, j) in sorted(pairs):
        length = math.ceil(dist(i, j) * rng.uniform(1.0, 1.25))
        up = rng.random() < 0.3                      # one direction is uphill (costs more energy)
        for (a, b, ef) in ((i, j, 1.5 if up else 1.0), (j, i, 1.0 if up else 1.5 if rng.random() < 0.1 else 1.0)):
            c = rng.choices([1.0, 1.3, 1.7, 2.2], weights=[50, 25, 15, 10])[0]
            t = math.ceil(length * c / speed) + wait[b]
            en = max(1, math.ceil(length * ef / 25))
            out[a].append(Edge(b, length, t, en))
    for (i, j) in sorted(pairs):
        if rng.random() < one_way_frac:
            drop = (i, j) if rng.random() < 0.5 else (j, i)
            saved = out[drop[0]]
            out[drop[0]] = [e for e in saved if e.to != drop[1]]
            if not _strongly_connected(n, out):
                out[drop[0]] = saved
    d = _Data()
    d.n = n; d.pos = {i: pts[i] for i in range(n)}; d.out = out
    d.inn = [[] for _ in range(n)]
    for u in range(n):
        for e in out[u]:
            d.inn[e.to].append((u, e))
    d.chargers = chargers; d.cap = cap; d.speed = speed; d.tc = charge_time
    d.seed = seed
    return d


def make_world(d, budget):
    """The object that is passed to your solve(). Calls to edges_from / edges_to are counted."""
    used = [0]
    def _count():
        used[0] += 1
        if used[0] > budget:
            raise BudgetExceeded("call budget (%d) exceeded" % budget)
    def edges_from(u):
        _count(); return tuple(d.out[u])
    def edges_to(v):
        _count(); return tuple(Edge(u, e.length, e.time, e.energy) for u, e in d.inn[v])
    # edges_to returns edges as seen from the target: Edge(to=<source building>, ...) meaning "you can arrive from .to"
    w = types.SimpleNamespace(
        nodes=tuple(range(d.n)), pos=dict(d.pos), chargers=d.chargers, capacity=d.cap,
        speed_max=d.speed, charge_time=d.tc, min_energy_per_meter=1.0 / 25,
        edges_from=edges_from, edges_to=edges_to, calls_used=lambda: used[0], budget=budget)
    return w


# ---------------- plan simulator (used by the grader) ----------------
def validate_plan(d, s, g, b0, plan):
    """Independent simulator. Returns (ok, total_time, message)."""
    u, b, t = s, b0, 0
    for k, act in enumerate(plan):
        if not isinstance(act, (tuple, list)) or not act:
            return False, 0, "action %d is malformed" % k
        if act[0] == "move":
            e = next((x for x in d.out[u] if x.to == act[1]), None)
            if e is None:
                return False, 0, "action %d: no road from %s to %s" % (k, u, act[1])
            if b < e.energy:
                return False, 0, "action %d: battery %d is not enough for %d" % (k, b, e.energy)
            u, b, t = e.to, b - e.energy, t + e.time
        elif act[0] == "charge":
            if u not in d.chargers:
                return False, 0, "action %d: building %s has no charger" % (k, u)
            if b >= d.cap:
                return False, 0, "action %d: battery already full" % k
            b, t = b + 1, t + d.tc
        else:
            return False, 0, "action %d: unknown action %r" % (k, act[0])
    if u != g:
        return False, 0, "plan ends at %s, not at the destination %s" % (u, g)
    return True, t, "ok"
